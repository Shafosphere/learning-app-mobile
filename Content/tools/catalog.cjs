const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const audio = require('../../Audio/tools/catalog.cjs');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const validPath = value => typeof value === 'string' && value.length > 0 && !value.startsWith('/') && !value.includes('\\') && value.split('/').every(p => p && p !== '.' && p !== '..');

function buildImages(root, definitions) {
  const dir = path.join(root, 'Content/packs/images');
  definitions ??= fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort().map(f => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
  const packs = {};
  for (const def of definitions) {
    if (!/^images_[a-z0-9_]+$/.test(def.id) || packs[def.id]) throw new Error(`Invalid/duplicate pack: ${def.id}`);
    if (typeof def.titleKey !== 'string' || !def.titleKey || !Object.keys(def.files ?? {}).length) throw new Error(`Empty image pack: ${def.id}`);
    const files = {};
    for (const [id, source] of Object.entries(def.files).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
      if (!validPath(id) || !validPath(source) || /^(content|audio)-manifests\//.test(id)) throw new Error(`Unsafe image path: ${id}`);
      const full = fs.realpathSync(path.resolve(root, source));
      if (!full.startsWith(fs.realpathSync(root) + path.sep) || !fs.statSync(full).isFile()) throw new Error(`Invalid image source: ${source}`);
      const bytes = fs.readFileSync(full);
      if (!bytes.length) throw new Error(`Empty image: ${source}`);
      files[id] = { relativePath: id, source, bytes: bytes.length, fileSha256: hash(bytes) };
    }
    const manifest = JSON.stringify({ schemaVersion: 3, packName: def.id, files: Object.values(files).map(({ relativePath, bytes, fileSha256 }) => ({ relativePath, bytes, fileSha256 })) }) + '\n';
    packs[def.id] = { kind: 'images', titleKey: def.titleKey, sourceBytes: Object.values(files).reduce((n, f) => n + f.bytes, 0), manifestHash: hash(manifest), manifest, files };
  }
  return { schemaVersion: 1, packs };
}
function validateDependencies(packs, courses) {
  for (const course of courses) for (const id of course.requiredImagePacks ?? []) {
    if (!packs[id]) throw new Error(`Unknown image pack ${id} in ${course.slug}`);
  }
}
function validatePackCount(packs) {
  if (Object.keys(packs).length > 100) throw new Error('Content exceeds 100 PAD packs');
}
function buildCatalog(root) {
  const images = buildImages(root), audioCatalog = audio.buildCatalog(root);
  // Read official definitions without importing React Native or asset requires.
  const { officialCourses } = require('./officialCourses.cjs');
  const courses = officialCourses(root);
  validateDependencies(images.packs, courses);
  const packs = { ...audioCatalog.packs, ...images.packs };
  validatePackCount(packs);
  return { images, audioCatalog, packs, courses };
}
function writeOutputs(root, catalog) {
  audio.writeOutputs(root, catalog.audioCatalog);
  const dir = path.join(root, 'Content/runtime/generated');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'courses.json'), JSON.stringify(Object.fromEntries(catalog.courses.filter(c => c.requiredImagePacks?.length).map(c => [c.slug, c.requiredImagePacks])), null, 2) + '\n');
  const runtime = { schemaVersion: 1, packs: Object.fromEntries(Object.entries(catalog.images.packs).map(([id, { manifest, ...pack }]) => [id, pack])) };
  fs.writeFileSync(path.join(dir, 'images.json'), JSON.stringify(runtime, null, 2) + '\n');
  const bundled = Object.entries(catalog.images.packs).map(([id, pack]) => `${JSON.stringify(id)}: {\n${Object.entries(pack.files).map(([key, f]) => `  ${JSON.stringify(key)}: require(${JSON.stringify('@/' + f.source)}),`).join('\n')}\n}`).join(',\n');
  fs.writeFileSync(path.join(dir, 'bundledImages.ts'), `/* Generated by content:prepare. */\nexport const usesImagePAD = false;\nexport const bundledImageSets: Record<string, Record<string, number>> = {\n${bundled}\n};\n`);
  fs.writeFileSync(path.join(dir, 'bundledImages.pad.ts'), `/* Generated by content:prepare. No bundled image imports. */\nexport const usesImagePAD = true;\nexport const bundledImageSets: Record<string, Record<string, number>> = ${JSON.stringify(Object.fromEntries(Object.keys(catalog.images.packs).map(id => [id, {}])))};\n`);
}
function gradleBlocks(catalog) {
  const blocks = audio.gradleBlocks(catalog);
  // React Native creates this directory but does not remove assets excluded by
  // a later bundle. Rebuild it so PAD migrations and delivery variants stay clean.
  blocks.app += `

// Remove stale Metro resources before writing the current bundle assets.
tasks.withType(com.facebook.react.tasks.BundleHermesCTask).configureEach {
    doFirst { bundleTask ->
        project.delete(bundleTask.resourcesDir.get().asFile)
    }
}`;
  return blocks;
}
function preparePacks(root, androidRoot, catalog) {
  // Each generator removes only modules carrying its own ownership marker.
  audio.preparePacks(root, androidRoot, { ...catalog.audioCatalog, packs: catalog.audioCatalog.packs });
  for (const name of fs.readdirSync(androidRoot)) {
    if (!catalog.images.packs[name] && fs.existsSync(path.join(androidRoot, name, '.content-pack-owned'))) fs.rmSync(path.join(androidRoot, name), { recursive: true });
  }
  for (const [name, pack] of Object.entries(catalog.images.packs)) {
    const dir = path.join(androidRoot, name), assets = path.join(dir, 'src/main/assets');
    if (fs.existsSync(dir) && !fs.existsSync(path.join(dir, '.content-pack-owned'))) throw new Error(`Refusing to replace unowned pack: ${name}`);
    fs.rmSync(assets, { recursive: true, force: true });
    fs.mkdirSync(path.join(assets, 'content-manifests'), { recursive: true });
    fs.writeFileSync(path.join(dir, '.content-pack-owned'), 'Generated by Content/tools.\n');
    fs.writeFileSync(path.join(dir, 'build.gradle'), `plugins { id 'com.android.asset-pack' }\nassetPack {\n    packName = '${name}'\n    dynamicDelivery { deliveryType = 'on-demand' }\n}\n`);
    fs.writeFileSync(path.join(assets, 'content-manifests', `${name}.json`), pack.manifest);
    for (const f of Object.values(pack.files)) {
      const target = path.join(assets, f.relativePath);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.copyFileSync(path.join(root, f.source), target);
    }
  }
}
module.exports = { buildImages, buildCatalog, writeOutputs, preparePacks, validateDependencies, validPath, validatePackCount, gradleBlocks, withBlock: audio.withBlock };
