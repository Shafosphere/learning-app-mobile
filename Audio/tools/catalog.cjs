const { join } = require('node:path');
const { readFileSync, existsSync, mkdirSync, writeFileSync, copyFileSync, rmSync, readdirSync } = require('node:fs');
const identity = require('./identity.cjs');
const { readJson, saveJson } = require('./io.cjs');
const sources = require('./sources.cjs');
const { mapCourses } = require('./mappings.cjs');
const { packRecordings } = require('./packing.cjs');
const { writeOutputs, runtimeCatalog } = require('./outputs.cjs');

function buildCatalog(projectRoot, documents = {}) {
  const root = join(projectRoot, 'Audio/content');
  const source = documents.recordings ?? sources.readRecordings(root);
  const recipes = documents.recipes ?? sources.readRecipes(root);
  sources.validateRecordings(root, source);
  const mapped = mapCourses(projectRoot, documents.courses ?? readJson(join(root, 'courses.json')), recipes, source);
  const packed = packRecordings(mapped.usedAudioIds, source);
  for (const course of Object.values(mapped.courses)) {
    const used = Object.values(course.cards).flatMap((sides) => Object.values(sides).flat());
    course.requiredPacks = [...new Set(used.map((id) => packed.recordings[id].packName))].sort();
  }
  for (const summary of mapped.summary) for (const row of summary.rows) row.pack = packed.recordings[row.audioId]?.packName ?? '';
  return { schemaVersion: 2, ...packed, courses: mapped.courses, summary: mapped.summary };
}

const START = '// @generated audio asset packs: start';
const END = '// @generated audio asset packs: end';
function withBlock(content, body) {
  const start = content.indexOf(START), end = content.indexOf(END);
  if ((start < 0) !== (end < 0) || (start >= 0 && end < start)) throw new Error('Malformed audio Gradle block');
  const block = `${START}\n${body}\n${END}`;
  return start < 0 ? `${content.trimEnd()}\n\n${block}\n` : `${content.slice(0, start)}${block}${content.slice(end + END.length)}`;
}
function gradleBlocks(catalog) {
  const names = Object.keys(catalog.packs);
  return { settings: names.map((name) => `include ':${name}'`).join('\n'),
    app: `android {\n    assetPacks += [${names.map((name) => `":${name}"`).join(', ')}]\n}` };
}
function ownedPack(root, name) {
  const gradle = join(root, name, 'build.gradle');
  return existsSync(join(root, name, '.audio-pack-owned')) ||
    (['audio_es_core', 'audio_fr_core'].includes(name) && existsSync(gradle) &&
      readFileSync(gradle, 'utf8').includes(`packName = '${name}'`) && readFileSync(gradle, 'utf8').includes("id 'com.android.asset-pack'"));
}
function preparePacks(projectRoot, androidRoot, catalog = buildCatalog(projectRoot)) {
  const source = sources.readRecordings(join(projectRoot, 'Audio/content'));
  for (const name of readdirSync(androidRoot)) {
    if (!catalog.packs[name] && ownedPack(androidRoot, name)) rmSync(join(androidRoot, name), { recursive: true, force: true });
  }
  for (const [packName, pack] of Object.entries(catalog.packs)) {
    const packRoot = join(androidRoot, packName), assets = join(packRoot, 'src/main/assets');
    if (existsSync(packRoot) && !ownedPack(androidRoot, packName)) throw new Error(`Refusing to replace unowned pack: ${packName}`);
    rmSync(assets, { recursive: true, force: true });
    mkdirSync(assets, { recursive: true });
    writeFileSync(join(packRoot, '.audio-pack-owned'), 'Generated by Audio/tools.\n');
    writeFileSync(join(packRoot, 'build.gradle'), `plugins { id 'com.android.asset-pack' }\nassetPack {\n    packName = '${packName}'\n    dynamicDelivery { deliveryType = 'on-demand' }\n}\n`);
    mkdirSync(join(assets, 'audio-manifests'), { recursive: true });
    writeFileSync(join(assets, 'audio-manifests', `${packName}.json`), pack.manifest);
    for (const id of pack.audioIds) copyFileSync(join(projectRoot, 'Audio/content', source[id].file), join(assets, `${id}.mp3`));
  }
}
module.exports = { ...identity, ...sources, buildCatalog, saveJson, preparePacks, gradleBlocks, withBlock, writeOutputs, runtimeCatalog };
