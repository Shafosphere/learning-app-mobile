const { join } = require('node:path');
const Papa = require('papaparse');
const { saveText, sorted } = require('./io.cjs');

function runtimeCatalog(catalog) {
  const entries = Object.entries(catalog.recordings), indexes = new Map(entries.map(([id], index) => [id, index]));
  return { schemaVersion: 2, languages: catalog.languages,
    recordings: entries.map(([audioId, { text, language, packName }]) => ({ audioId, text, language, packName })),
    packs: Object.fromEntries(Object.entries(catalog.packs).map(([name, pack]) => [name,
      { language: pack.language, deliveryMode: pack.deliveryMode, sourceBytes: pack.sourceBytes, recordingCount: pack.audioIds.length, manifestHash: pack.manifestHash }])),
    courses: Object.fromEntries(Object.entries(catalog.courses).map(([slug, course]) => [slug, { ...course,
      cards: Object.fromEntries(Object.entries(course.cards).map(([id, sides]) => [id,
        Object.fromEntries(Object.entries(sides).map(([side, ids]) => [side, Array.isArray(ids) ? ids.map((id) => indexes.get(id)) : indexes.get(ids)]))])) }])) };
}
function writeOutputs(root, catalog) {
  saveText(join(root, 'Audio/runtime/generated/catalog.json'), `${JSON.stringify(runtimeCatalog(catalog))}\n`);
  const report = ['# Audio — generated report', '', 'Generated by `npm run audio:prepare`. Edit source configuration, not this report.', '',
    `Recordings: ${Object.keys(catalog.recordings).length}. Packs: ${Object.keys(catalog.packs).length}.`, '',
    '| Course | Cards | Matched forms | Missing forms | MP3 MB | Required packs |', '| --- | ---: | ---: | ---: | ---: | --- |'];
  for (const item of catalog.summary) {
    const packs = catalog.courses[item.slug].requiredPacks;
    const bytes = packs.reduce((sum, name) => sum + catalog.packs[name].sourceBytes, 0);
    report.push(`| ${item.slug} | ${item.totalCards} | ${item.matched} | ${item.missing} | ${(bytes / 1e6).toFixed(2)} | ${packs.join(', ')} |`);
    saveText(join(root, 'Audio/content/reports', `${item.slug}.csv`), `${Papa.unparse(item.rows, { newline: '\n', columns: ['externalId', 'side', 'text', 'audioId', 'pack'] })}\n`);
  }
  report.push('', '## Packs', '', '| Pack | Recordings | MP3 bytes |', '| --- | ---: | ---: |');
  for (const [name, pack] of Object.entries(sorted(catalog.packs))) report.push(`| ${name} | ${pack.audioIds.length} | ${pack.sourceBytes} |`);
  report.push('', 'MP3 sizes are uncompressed source bytes. Google Play reports actual transfer sizes.', '');
  saveText(join(root, 'docs/audio/content/reports/README.md'), report.join('\n'));
}
module.exports = { runtimeCatalog, writeOutputs };
