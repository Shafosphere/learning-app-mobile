import fs from "node:fs";
import path from "node:path";
import { ATTRIBUTION_COURSES, type AttributionCourseRegistryEntry } from "../attributions/courseRegistry.ts";

type TsvRow = Record<string, string>;

const REQUIRED_COLUMNS = [
  "nr",
  "nazwa_polska",
  "nazwa_lacinska",
  "nazwa_pliku",
  "link_do_obrazu_i_strony_licencji",
  "licencja",
  "autor_do_atrybucji",
] as const;

const ROOT_DIR = process.cwd();
const OUTPUT_PATH = path.join(ROOT_DIR, "src/data/generatedImageAttributions.ts");

function fail(sourcePath: string, rowNumber: number, message: string): never {
  throw new Error(`${sourcePath}: row ${rowNumber}: ${message}`);
}

function isValidUrl(value: string) {
  try {
    const url = new URL(value);
    return url.protocol === "https:" || url.protocol === "http:";
  } catch {
    return false;
  }
}

function titleFromFileName(fileName: string) {
  return fileName.replace(/\.[^.]+$/, "");
}

function parseTsv(sourcePath: string) {
  const input = fs.readFileSync(path.join(ROOT_DIR, sourcePath), "utf8").replace(/^\uFEFF/, "");
  const lines = input.trimEnd().split(/\r?\n/);
  if (lines.length < 2) throw new Error(`${sourcePath}: no attribution rows`);

  const headers = lines[0].split("\t");
  for (const column of REQUIRED_COLUMNS) {
    if (!headers.includes(column)) throw new Error(`${sourcePath}: missing column "${column}"`);
  }

  return lines.slice(1).map((line, index) => {
    const values = line.split("\t");
    const row = Object.fromEntries(headers.map((header, column) => [header, values[column]?.trim() ?? ""])) as TsvRow;
    return { row, rowNumber: index + 2 };
  });
}

export function parseAttributionCourse(course: AttributionCourseRegistryEntry) {
  const seenIds = new Set<string>();
  const attributions = parseTsv(course.sourcePath).map(({ row, rowNumber }) => {
    for (const column of REQUIRED_COLUMNS) {
      if (!row[column]) fail(course.sourcePath, rowNumber, `missing required field "${column}"`);
    }
    if (seenIds.has(row.nr)) fail(course.sourcePath, rowNumber, `duplicate nr "${row.nr}"`);
    seenIds.add(row.nr);

    if (!isValidUrl(row.link_do_obrazu_i_strony_licencji)) {
      fail(course.sourcePath, rowNumber, "invalid source URL");
    }
    if (row.licencja !== "Public domain" && !isValidUrl(row.link_do_tekstu_licencji)) {
      fail(course.sourcePath, rowNumber, "invalid license URL");
    }

    const changes = row.opis_zmian || course.defaultChanges.pl;
    return {
      id: row.nr,
      commonName: row.nazwa_polska,
      scientificName: row.nazwa_lacinska,
      title: row.tytul_do_atrybucji || titleFromFileName(row.nazwa_pliku),
      author: row.autor_do_atrybucji,
      sourceUrl: row.link_do_obrazu_i_strony_licencji,
      license: row.licencja,
      licenseUrl: isValidUrl(row.link_do_tekstu_licencji) ? row.link_do_tekstu_licencji : undefined,
      changes: {
        pl: changes,
        en: row.opis_zmian ? changes : course.defaultChanges.en,
      },
    };
  });

  return { id: course.id, title: course.title, attributions };
}

export function buildImageAttributions(courses = ATTRIBUTION_COURSES) {
  const ids = new Set<string>();
  for (const course of courses) {
    if (!course.id) throw new Error("Attribution course has no id");
    if (ids.has(course.id)) throw new Error(`Duplicate attribution course id "${course.id}"`);
    ids.add(course.id);
  }
  return courses.map(parseAttributionCourse);
}

export function generateImageAttributions(outputPath = OUTPUT_PATH) {
  const courses = buildImageAttributions();
  const content = [
    'import type { ImageAttributionCourse } from "@/src/data/imageAttributions";',
    "",
    "// Generated by npm run assets:attributions. Do not edit manually.",
    `export const IMAGE_ATTRIBUTION_COURSES: ImageAttributionCourse[] = ${JSON.stringify(courses, null, 2)};`,
    "",
  ].join("\n");
  const temporaryPath = `${outputPath}.tmp`;
  fs.writeFileSync(temporaryPath, content, "utf8");
  fs.renameSync(temporaryPath, outputPath);
  return courses;
}

if (process.argv[1]?.endsWith("build-image-attributions.ts")) {
  const courses = generateImageAttributions();
  console.log(`Generated ${courses.reduce((count, course) => count + course.attributions.length, 0)} image attributions.`);
}
